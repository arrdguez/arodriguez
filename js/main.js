const SCO = {
  Dq0: 1500,
  P: 20000,
  kB: 0.695,
  xMin: 0.85,
  xMax: 1.35,
  xc: Math.pow((20 * 1500) / 20000, 1 / 5)
};

let scoX = SCO.xc;
let scoT = 300;
